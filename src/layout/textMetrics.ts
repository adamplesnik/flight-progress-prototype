const FALLBACK = 620

/** Width of `text` in px (without kerning, so very slightly generous). */
export function textWidth(text: string, size: number, weight: 400 | 600) {
  const table = weight === 600 ? SEMIBOLD : REGULAR
  let width = 0
  for (const char of text) width += table[char] ?? FALLBACK
  return (width / 1000) * size
}
