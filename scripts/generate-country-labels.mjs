// Generates src/countryLabels.ts: one label position per country that can fit its name
// (16px regular text) fully inside its outline. Run: node scripts/generate-country-labels.mjs
import { readFileSync, writeFileSync } from "node:fs"

const FONT_SIZE = 16
const PAD = 3 // minimum clearance (map units) left and right of the text
const svg = readFileSync("public/assets/150bf.svg", "utf8")

const regionNames = new Intl.DisplayNames(["en"], { type: "region" })
const overrides = {
  China: "China", USA: "United States", CD: "DR Congo", CG: "Congo", MM: "Myanmar",
  CI: "Côte d’Ivoire", BA: "Bosnia & Herz.", CF: "Central African Rep.", SS: "South Sudan",
  GQ: "Eq. Guinea", MK: "North Macedonia", CZ: "Czechia", TL: "Timor-Leste", XK: "Kosovo",
  KP: "North Korea", KR: "South Korea", LA: "Laos", PS: "Palestine", DO: "Dominican Rep.",
  EH: "W. Sahara", SZ: "Eswatini", GL: "Greenland", AE: "UAE",
}

// Rough Inter Regular advance widths in em
const narrow = new Set("ijltfr’.,' I".split(""))
const wide = new Set("mwMW".split(""))
function textWidth(s) {
  let w = 0
  for (const c of s) {
    if (c === " ") w += 0.28
    else if (narrow.has(c)) w += 0.3
    else if (wide.has(c)) w += 0.88
    else if (c >= "A" && c <= "Z") w += 0.68
    else w += 0.56
  }
  return w * FONT_SIZE
}

function parse(d) {
  const polys = []
  let cur = null, x = 0, y = 0
  for (const [, cmd, args] of d.matchAll(/([MLHVZ])([^MLHVZ]*)/g)) {
    const n = args.trim().split(/[\s,]+/).filter(Boolean).map(Number)
    if (cmd === "M") { cur = []; polys.push(cur); x = n[0]; y = n[1]; cur.push([x, y]) }
    else if (cmd === "L") { x = n[0]; y = n[1]; cur.push([x, y]) }
    else if (cmd === "H") { x = n[0]; cur.push([x, y]) }
    else if (cmd === "V") { y = n[0]; cur.push([x, y]) }
  }
  return polys
}

function rowIntervals(polys, y) {
  const xs = []
  for (const p of polys)
    for (let i = 0; i < p.length; i++) {
      const [x1, y1] = p[i], [x2, y2] = p[(i + 1) % p.length]
      if ((y1 <= y) !== (y2 <= y)) xs.push(x1 + ((y - y1) / (y2 - y1)) * (x2 - x1))
    }
  xs.sort((a, b) => a - b)
  const out = []
  for (let i = 0; i + 1 < xs.length; i += 2) out.push([xs[i], xs[i + 1]])
  return out
}

const labels = []
for (const [, id, d] of svg.matchAll(/<path id="([^"]+)" d="([^"]+)"/g)) {
  if (id.startsWith("Vector") || id.startsWith("BQ")) continue
  let name = overrides[id]
  if (!name) { try { name = regionNames.of(id) } catch { continue } }
  if (!name || name === id) continue
  const polys = parse(d)
  const all = polys.flat()
  const minX = Math.min(...all.map((p) => p[0])), maxX = Math.max(...all.map((p) => p[0]))
  const minY = Math.min(...all.map((p) => p[1])), maxY = Math.max(...all.map((p) => p[1]))
  const W = textWidth(name)
  if (maxX - minX < W + 2 * PAD || maxY - minY < FONT_SIZE) continue
  const rows = new Map()
  const rowAt = (y) => { const k = Math.round(y); if (!rows.has(k)) rows.set(k, rowIntervals(polys, k + 0.01)); return rows.get(k) }
  const centroid = [(minX + maxX) / 2, (minY + maxY) / 2]
  let best = null
  for (let cy = minY + 8; cy <= maxY - 8; cy += 2) {
    const sample = []
    for (let dy = -6; dy <= 6; dy += 3) sample.push(rowAt(cy + dy))
    // candidate x positions from the middle row's intervals
    for (const [l, r] of sample[2]) {
      for (let cx = l + W / 2; cx <= r - W / 2; cx += 2) {
        let slack = Infinity
        for (const iv of sample) {
          const hit = iv.find(([a, b]) => a <= cx - W / 2 && b >= cx + W / 2)
          if (!hit) { slack = -1; break }
          slack = Math.min(slack, cx - W / 2 - hit[0], hit[1] - cx - W / 2)
        }
        if (slack < PAD) continue
        const score = slack - 0.02 * Math.hypot(cx - centroid[0], cy - centroid[1])
        if (!best || score > best.score) best = { score, x: cx, y: cy }
      }
    }
  }
  if (best) labels.push({ id, name, x: +best.x.toFixed(1), y: +best.y.toFixed(1) })
}

writeFileSync(
  "src/countryLabels.ts",
  `// Generated by scripts/generate-country-labels.mjs — do not edit by hand.\n// Coordinates are in the world map SVG's own units (4003.05 × 1721.37).\nexport type CountryLabel = { id: string; name: string; x: number; y: number }\n\nexport const countryLabels: CountryLabel[] = ${JSON.stringify(labels, null, 1).replace(/\n\s*/g, " ").replace(/\}, \{/g, "},\n  {").replace("[ {", "[\n  {").replace(/ \]$/, "\n]")}\n`,
)
